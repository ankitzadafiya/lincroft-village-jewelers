export function thumb(url: string): string {
  if (url.includes('etsystatic.com')) {
    return url
      .replace(/il_\d+xN/g, 'il_340x270')
      .replace(/il_\d+x\d+/g, 'il_340x270');
  }
  return url
    .replace('w=1200', 'w=480')
    .replace('w=1400', 'w=480')
    .replace('w=1600', 'w=640')
    .replace('w=1920', 'w=800');
}
